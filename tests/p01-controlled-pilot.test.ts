/**
 * P01 controlled-pilot test harness.
 *
 * Authority: docs/P01_CONTROLLED_PILOT.md (P01 WP spec).
 *
 * This is NOT a unit test. It is the S05A-style "smallest
 * runnable check that fails if the integration breaks" for
 * the entire S01..S05A pipeline. The pilot drives a real
 * extension instance end-to-end through three work packages,
 * one forced PRESSURE rollover, one oversized tool result,
 * one recovery, and a process-restart durability check.
 *
 * The pilot is intentionally synthetic at the LLM layer — we
 * do not have an LLM in this sandbox — but it is REAL at the
 * runtime layer: the real `cmv3Extension` entry, the real S02
 * store, the real S04 orchestrator, the real S05A pressure
 * trigger, and the real S05 tool-result virtualization.
 *
 * Limitations (called out explicitly in
 * docs/P01_PILOT_REPORT.md):
 *   - LLM is replaced by a small test driver that calls the
 *     registered tool and command handlers with valid inputs.
 *   - The "operator" is the test driver, not a human.
 *   - All other surfaces are real.
 *
 * The pilot writes docs/P01_PILOT_REPORT.md on success. The
 * file is regenerated by every `npm test` run; CI / operator
 * can grep the report for any gate field.
 */

