interface WorkPackage {
	id: string;
	title: string;
	goal: string;
	work_package: string;
	status: "COMPLETE" | "IN_PROGRESS" | "BLOCKED";
	completed: string[];
	in_progress: string[];
	blockers: string[];
	important_decisions: string[];
	hard_constraints: string[];
	current_files: string[];
	active_errors: string[];
	next_actions: string[];
	recovery_refs?: { kind: string; id: string; uri: string }[];
}

async function prepareRolloverForWP(
	env: PilotEnv,
	projectId: string,
	sessionId: string,
	wp: WorkPackage,
): Promise<{ ref: string; id: string }> {
	const prepare = env.toolHandlers.get(ROLLOVER_TOOL_NAME);
	assert.ok(prepare, "picm_prepare_rollover not registered");
	// Build the args object as a typed const first; the
	// downstream call uses the const, not an inline
	// interpolated expression, to keep the call site
	// statically shape-checked.
	const toolArgs = {
		reason: (wp.status === "IN_PROGRESS" ? "PRESSURE" : "NATURAL") as
			| "PRESSURE"
			| "NATURAL",
		goal: wp.goal,
		work_package: wp.work_package,
		status: wp.status,
		completed: wp.completed,
		in_progress: wp.in_progress,
		blockers: wp.blockers,
		important_decisions: wp.important_decisions,
		hard_constraints: wp.hard_constraints,
		current_files: wp.current_files,
		active_errors: wp.active_errors,
		next_actions: wp.next_actions,
		recovery_refs: wp.recovery_refs ?? [],
	};
	const out = (await prepare.execute("p01-prepare-" + wp.id, toolArgs)) as {
		details: { ref: string; id: string };
	};
	void projectId;
	void sessionId;
	return { ref: out.details.ref, id: out.details.id };
}

async function executeRollover(
	env: PilotEnv,
	id: string,
	ctx: SyntheticCtx,
): Promise<void> {
	const cmd = env.commandHandlers.get(ROLLOVER_COMMAND_NAME);
	assert.ok(cmd, "picm-rollover-execute not registered");
	await cmd.handler(id, ctx);
}

