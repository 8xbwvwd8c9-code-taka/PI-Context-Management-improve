/**
 * Portable core — tool result contract.
 *
 * Authority: docs/CMV3_PORTABLE_ARCHITECTURE_FREEZE.md §8, §9, §10.
 *
 * S03 implements the data plane for tool-result virtualization.
 * This module is PURE: no I/O, no Pi, no host project. The
 * persistence / integrity / range-read layer lives in
 * `src/store/tool-result-store.ts`.
 *
 * Canonical lifecycle (R02 §9):
 *
 *   full tool result
 *   → durable persistence
 *   → integrity verification / reference
 *   → bounded active representation
 *   → recover on demand
 *
 * Hard invariant: persistence happens FIRST. A bounded active view
 * is produced only after the full authoritative bytes are on disk
 * and their SHA-256 is verified. The active view must be MUCH
 * smaller than an oversized raw payload so the agent can decide
 * whether to recover more.
 *
 * Tool output is UNTRUSTED DATA. Payload bytes may contain text
 * that LOOKS like instructions (e.g. "ignore previous instructions",
 * fake SYSTEM/DEVELOPER blocks, fake A2A reports). Those strings
 * MUST remain payload data only and MUST NOT influence PICM control
 * flow. PICM does not interpret, parse, summarize, or extract
 * commands from tool payloads.
 *
 * Generic contract: this module does NOT assume one host project's
 * tools. It works for shell/exec, tests, build, grep/search, file
 * output, HTTP/tool connector output, structured JSON, text, and
 * arbitrary binary. No tool-specific strings appear in the schema.
 */

import { parseRef, type ParsedRef, type RefKind } from "./refs.js";

export const TOOL_RESULT_SCHEMA_VERSION = "1.0.0" as const;
export const TOOL_RESULT_METADATA_SCHEMA_VERSION = "1.0.0" as const;

export const TOOL_RESULT_REF_KIND: RefKind = "tool";

/**
 * Generic kind hint. The exact value is opaque to PICM: it is
 * recorded as metadata only and never interpreted as control flow.
 * Hosts may pass any non-empty lowercase-ish string; PICM does
 * not depend on the value.
 *
 * Examples (NOT a closed list):
 *   "text" | "json" | "binary" | "log" | "exec" | "test" | "search"
 */
export type ToolResultKind = string;

/**
 * Authoritative tool-result metadata persisted alongside the full
 * payload bytes. The metadata file is the on-disk record; the
 * payload is a separate artifact. Both share the same opaque id.
 *
 * PICM never stores:
 *   - the raw payload in this metadata file
 *   - parsed "commands" extracted from the payload
 *   - secret-shaped strings
 *
 * The id is the only stable handle. It is generated by the store
 * via CSPRNG; callers do not choose it.
 */
export interface ToolResultMetadata {
	readonly schema_version: typeof TOOL_RESULT_METADATA_SCHEMA_VERSION;
	readonly tool_result_id: string;
	readonly project_id: string;
	readonly session_id: string | null;
	readonly created_at: string; // ISO-8601

	readonly tool_name: string;
	readonly tool_call_id: string | null;
	readonly result_kind: ToolResultKind;

	readonly exit_code: number | null;
	readonly success: boolean | null;

	readonly original_bytes: number;
	readonly stored_bytes: number;
	readonly active_excerpt_bytes: number;
	readonly truncated_in_active_view: boolean;

	readonly content_hash: string; // hex SHA-256 over authoritative bytes
	readonly encoding: "utf-8" | "binary";
	readonly mime_type: string | null;

	/**
	 * Canonical tool-result ref. Opaque, project-isolated on lookup.
	 */
	readonly ref: string;
}

/**
 * Bounded active representation of a tool result. The active view
 * is the only thing that lives in active context; the full bytes
 * are on disk behind a ref.
 *
 * The view is deterministic and configurable. It is intentionally
 * MUCH smaller than the raw payload for oversized results; the
 * intent is "the agent can decide whether to recover more" — never
 * "the agent sees the full thing".
 *
 * For small results the active view carries the full body inline
 * and `truncated=false`. There is no LLM summarization; the
 * representation is mechanical.
 */
export interface ToolResultActiveView {
	readonly ref: string;
	readonly tool_name: string;
	readonly tool_call_id: string | null;
	readonly result_kind: ToolResultKind;
	readonly success: boolean | null;
	readonly exit_code: number | null;
	readonly original_bytes: number;
	readonly stored_bytes: number;
	readonly active_excerpt_bytes: number;
	readonly truncated: boolean;
	readonly content_hash: string;
	readonly mime_type: string | null;
	/**
	 * Bounded excerpt. May be the full body for small results, or
	 * head + marker + tail for oversized results. The shape is
	 * documented in `docs/TOOL_RESULT_VIRTUALIZATION.md`.
	 */
	readonly excerpt: string;
	/**
	 * When `excerpt` was reconstructed from a non-UTF-8 byte stream
	 * (or the bytes were binary), the excerpt may be a lossy
	 * summary. The full bytes are still recoverable exactly via
	 * the ref. This flag is metadata, not a hint to the agent.
	 */
	readonly excerpt_is_lossy: boolean;
}

/**
 * Active view policy. S03 keeps the policy simple: a deterministic
 * head/tail window when the payload is larger than the active-view
 * budget. The budget may be derived from a CMV3 profile's
 * `output_reserve`; the store does not depend on the profile and
 * accepts a byte budget directly.
 */
export interface ActiveViewPolicy {
	/**
	 * Maximum total bytes included in `excerpt`. The default is
	 * generous on purpose (matches the `output_reserve` of the
	 * `local_32k` profile when used in concert) and is NOT tied
	 * to one host project. Callers may tighten it.
	 */
	readonly maxExcerptBytes: number;
	/**
	 * Bytes reserved for the head of the excerpt.
	 */
	readonly headBytes: number;
	/**
	 * Bytes reserved for the tail of the excerpt.
	 */
	readonly tailBytes: number;
	/**
	 * Marker inserted between head and tail when truncated. The
	 * marker is a stable ASCII string; PICM does not interpret it
	 * as a command.
	 */
	readonly marker: string;
	/**
	 * If true and the bytes decode cleanly as UTF-8, the excerpt
	 * preserves the decoded string. If false or the bytes are
	 * binary, the excerpt is a safe lossy summary (size + first /
	 * last printable runs).
	 */
	readonly safeUtf8Decode: boolean;
}

/**
 * Default active view policy. Conservative: 4 KiB total budget,
 * 2 KiB head, ~1.95 KiB tail (reserving room for the marker).
 * Matches the `output_reserve` of the `local_32k` profile as a
 * default; S04+ / S05 may rebind it.
 *
 * The default is intentionally NOT the old host-specific 200 KB
 * cap. PICM has its own bounded active-view policy.
 */
export const DEFAULT_ACTIVE_VIEW_POLICY: Readonly<ActiveViewPolicy> = Object.freeze({
	maxExcerptBytes: 4096,
	headBytes: 2048,
	tailBytes: 1980,
	marker: "\n…[truncated tool output; recover via ref]…\n",
	safeUtf8Decode: true,
});

/**
 * Minimum / maximum bounds for the active view policy. The store
 * must reject policies that would silently swallow the entire
 * payload (headBytes + tailBytes + marker <= 0) or overflow the
 * Node.js Buffer range.
 */
export const ACTIVE_VIEW_BOUNDS = Object.freeze({
	minHeadBytes: 16,
	minTailBytes: 0,
	minMaxExcerpt: 64,
	maxExcerptBytes: 16 * 1024 * 1024, // 16 MiB hard ceiling
});

/**
 * Validate an active view policy. Throws on invalid input.
 */
export function validateActiveViewPolicy(p: unknown): ActiveViewPolicy {
	if (typeof p !== "object" || p === null) {
		throw new Error("validateActiveViewPolicy: input must be an object");
	}
	const v = p as Record<string, unknown>;
	if (typeof v.maxExcerptBytes !== "number" || !Number.isFinite(v.maxExcerptBytes)) {
		throw new Error("validateActiveViewPolicy: maxExcerptBytes must be a finite number");
	}
	if (typeof v.headBytes !== "number" || !Number.isFinite(v.headBytes)) {
		throw new Error("validateActiveViewPolicy: headBytes must be a finite number");
	}
	if (typeof v.tailBytes !== "number" || !Number.isFinite(v.tailBytes)) {
		throw new Error("validateActiveViewPolicy: tailBytes must be a finite number");
	}
	if (typeof v.marker !== "string") {
		throw new Error("validateActiveViewPolicy: marker must be a string");
	}
	if (typeof v.safeUtf8Decode !== "boolean") {
		throw new Error("validateActiveViewPolicy: safeUtf8Decode must be a boolean");
	}
	if (v.headBytes < ACTIVE_VIEW_BOUNDS.minHeadBytes) {
		throw new Error(
			`validateActiveViewPolicy: headBytes must be >= ${ACTIVE_VIEW_BOUNDS.minHeadBytes}`,
		);
	}
	if (v.tailBytes < ACTIVE_VIEW_BOUNDS.minTailBytes) {
		throw new Error(
			`validateActiveViewPolicy: tailBytes must be >= ${ACTIVE_VIEW_BOUNDS.minTailBytes}`,
		);
	}
	if (v.maxExcerptBytes < ACTIVE_VIEW_BOUNDS.minMaxExcerpt) {
		throw new Error(
			`validateActiveViewPolicy: maxExcerptBytes must be >= ${ACTIVE_VIEW_BOUNDS.minMaxExcerpt}`,
		);
	}
	if (v.maxExcerptBytes > ACTIVE_VIEW_BOUNDS.maxExcerptBytes) {
		throw new Error(
			`validateActiveViewPolicy: maxExcerptBytes must be <= ${ACTIVE_VIEW_BOUNDS.maxExcerptBytes}`,
		);
	}
	if (v.headBytes + v.tailBytes + Buffer.byteLength(v.marker, "utf8") > v.maxExcerptBytes) {
		throw new Error(
			"validateActiveViewPolicy: headBytes + tailBytes + marker must be <= maxExcerptBytes",
		);
	}
	return Object.freeze({
		maxExcerptBytes: v.maxExcerptBytes,
		headBytes: v.headBytes,
		tailBytes: v.tailBytes,
		marker: v.marker,
		safeUtf8Decode: v.safeUtf8Decode,
	}) as ActiveViewPolicy;
}

/**
 * Validate a tool-result metadata record. Returns the input on
 * success; throws on the first violation. Pure.
 *
 * The validation does NOT touch the filesystem and does NOT
 * interpret the payload. The `ref` field is structural-only here;
 * the store is responsible for issuing refs and for project
 * isolation at lookup time.
 */
export function validateToolResultMetadata(input: unknown): ToolResultMetadata {
	if (typeof input !== "object" || input === null) {
		throw new Error("validateToolResultMetadata: input must be an object");
	}
	const r = input as Record<string, unknown>;

	if (r.schema_version !== TOOL_RESULT_METADATA_SCHEMA_VERSION) {
		throw new Error(
			`validateToolResultMetadata: schema_version must be ${TOOL_RESULT_METADATA_SCHEMA_VERSION} (got ${String(r.schema_version)})`,
		);
	}
	requireString(r, "tool_result_id", "tool_result");
	requireString(r, "project_id", "tool_result");
	requireString(r, "created_at", "tool_result");
	requireString(r, "tool_name", "tool_result");
	requireString(r, "content_hash", "tool_result");
	requireString(r, "ref", "tool_result");

	if (r.session_id != null && typeof r.session_id !== "string") {
		throw new Error("validateToolResultMetadata: session_id must be a string or null");
	}
	if (r.tool_call_id != null && typeof r.tool_call_id !== "string") {
		throw new Error("validateToolResultMetadata: tool_call_id must be a string or null");
	}
	if (r.result_kind != null && typeof r.result_kind !== "string") {
		throw new Error("validateToolResultMetadata: result_kind must be a string");
	}
	if (r.mime_type != null && typeof r.mime_type !== "string") {
		throw new Error("validateToolResultMetadata: mime_type must be a string or null");
	}

	if (r.exit_code != null && typeof r.exit_code !== "number") {
		throw new Error("validateToolResultMetadata: exit_code must be a number or null");
	}
	if (r.success != null && typeof r.success !== "boolean") {
		throw new Error("validateToolResultMetadata: success must be a boolean or null");
	}

	if (typeof r.original_bytes !== "number" || r.original_bytes < 0) {
		throw new Error("validateToolResultMetadata: original_bytes must be a non-negative number");
	}
	if (typeof r.stored_bytes !== "number" || r.stored_bytes < 0) {
		throw new Error("validateToolResultMetadata: stored_bytes must be a non-negative number");
	}
	if (typeof r.active_excerpt_bytes !== "number" || r.active_excerpt_bytes < 0) {
		throw new Error(
			"validateToolResultMetadata: active_excerpt_bytes must be a non-negative number",
		);
	}
	if (typeof r.truncated_in_active_view !== "boolean") {
		throw new Error("validateToolResultMetadata: truncated_in_active_view must be a boolean");
	}

	if (r.encoding !== "utf-8" && r.encoding !== "binary") {
		throw new Error(
			`validateToolResultMetadata: encoding must be "utf-8" or "binary" (got ${String(r.encoding)})`,
		);
	}

	// content_hash must be 64-char lowercase hex (SHA-256).
	if (typeof r.content_hash !== "string" || !/^[0-9a-f]{64}$/.test(r.content_hash)) {
		throw new Error(
			"validateToolResultMetadata: content_hash must be a 64-char lowercase hex SHA-256 digest",
		);
	}

	// ref must parse as a tool ref.
	if (typeof r.ref !== "string") {
		throw new Error("validateToolResultMetadata: ref must be a string");
	}
	const parsed: ParsedRef | null = parseRef(r.ref);
	if (parsed === null || parsed.kind !== TOOL_RESULT_REF_KIND) {
		throw new Error(
			`validateToolResultMetadata: ref must be a valid cmv3://tool/ ref (got ${String(r.ref)})`,
		);
	}
	if (parsed.id !== r.tool_result_id) {
		throw new Error(
			"validateToolResultMetadata: ref id must equal tool_result_id",
		);
	}

	return r as unknown as ToolResultMetadata;
}

function requireString(
	o: Record<string, unknown>,
	key: string,
	owner: string,
): void {
	if (typeof o[key] !== "string" || (o[key] as string).length === 0) {
		throw new Error(`validate${cap(owner)}: ${key} must be a non-empty string`);
	}
}

function cap(s: string): string {
	return s.charAt(0).toUpperCase() + s.slice(1);
}

/* -------------------------------------------------------------------- *
 * Active-view construction (pure, deterministic)                        *
 * -------------------------------------------------------------------- */

/**
 * Build the bounded active view for a given byte payload.
 *
 *   - For payloads that fit within the budget: the full body is
 *     returned verbatim (decoded as UTF-8 if possible). `truncated`
 *     is `false`.
 *   - For oversized payloads: a head + marker + tail window is
 *     returned. The window is byte-aligned; the head and tail
 *     slices are returned in their UTF-8 decoded form when they
 *     decode cleanly. `truncated` is `true`.
 *   - For non-UTF-8 (binary) payloads: a safe lossy summary is
 *     returned. The full bytes are still recoverable exactly via
 *     the ref. `excerpt_is_lossy` is `true`.
 *
 * The function is pure. It does NOT decide what bytes are
 * "interesting" — head/tail preservation is the policy. The agent
 * is responsible for inspecting the excerpt and deciding whether
 * to recover more.
 */
export function buildActiveView(
	bytes: Uint8Array,
	policy: ActiveViewPolicy,
	opts: {
		ref: string;
		tool_name: string;
		tool_call_id: string | null;
		result_kind: ToolResultKind;
		success: boolean | null;
		exit_code: number | null;
		content_hash: string;
		mime_type: string | null;
	},
): ToolResultActiveView {
	const originalBytes = bytes.length;
	const decoded = tryDecodeUtf8(bytes);
	const isUtf8 = decoded !== null;

	if (originalBytes <= policy.maxExcerptBytes) {
		const excerpt = isUtf8
			? (decoded as string)
			: lossySummary(bytes, policy);
		return {
			ref: opts.ref,
			tool_name: opts.tool_name,
			tool_call_id: opts.tool_call_id,
			result_kind: opts.result_kind,
			success: opts.success,
			exit_code: opts.exit_code,
			original_bytes: originalBytes,
			stored_bytes: originalBytes,
			active_excerpt_bytes: Buffer.byteLength(excerpt, "utf8"),
			truncated: false,
			content_hash: opts.content_hash,
			mime_type: opts.mime_type,
			excerpt,
			excerpt_is_lossy: !isUtf8,
		};
	}

	// Oversized: head + marker + tail.
	const head = bytes.subarray(0, policy.headBytes);
	const tail = policy.tailBytes > 0 ? bytes.subarray(bytes.length - policy.tailBytes) : new Uint8Array();

	let headStr: string;
	let tailStr: string;
	let lossy = false;
	if (isUtf8) {
		headStr = new TextDecoder("utf-8", { fatal: true }).decode(head);
		tailStr = policy.tailBytes > 0 ? new TextDecoder("utf-8", { fatal: true }).decode(tail) : "";
	} else {
		headStr = lossyHeadTail(head, tail, policy.marker);
		tailStr = "";
		lossy = true;
	}

	const excerpt = headStr + policy.marker + tailStr;
	const excerptBytes = Buffer.byteLength(excerpt, "utf8");
	return {
		ref: opts.ref,
		tool_name: opts.tool_name,
		tool_call_id: opts.tool_call_id,
		result_kind: opts.result_kind,
		success: opts.success,
		exit_code: opts.exit_code,
		original_bytes: originalBytes,
		stored_bytes: originalBytes,
		active_excerpt_bytes: excerptBytes,
		truncated: true,
		content_hash: opts.content_hash,
		mime_type: opts.mime_type,
		excerpt,
		excerpt_is_lossy: lossy,
	};
}

function tryDecodeUtf8(bytes: Uint8Array): string | null {
	// Buffer can decode any byte sequence as utf-8 (it replaces
	// invalid sequences with U+FFFD). We use a streaming decoder
	// with `fatal: true` to detect non-UTF-8 byte sequences, which
	// then triggers the lossy path.
	try {
		const dec = new TextDecoder("utf-8", { fatal: true });
		return dec.decode(bytes);
	} catch {
		return null;
	}
}

function lossySummary(bytes: Uint8Array, policy: ActiveViewPolicy): string {
	const head = bytes.subarray(0, policy.headBytes);
	const tail = policy.tailBytes > 0 ? bytes.subarray(bytes.length - policy.tailBytes) : new Uint8Array();
	return lossyHeadTail(head, tail, policy.marker);
}

function lossyHeadTail(head: Uint8Array, tail: Uint8Array, marker: string): string {
	const printable = (b: Uint8Array): string => {
		let out = "";
		let lastWasNewline = true;
		for (let i = 0; i < b.length; i++) {
			const c = b[i];
			// ASCII printable range + tab + newline; everything
			// else becomes a single dot.
			if (c === 0x09 || c === 0x0a || c === 0x0d || (c >= 0x20 && c <= 0x7e)) {
				out += String.fromCharCode(c);
				lastWasNewline = c === 0x0a;
			} else if (!lastWasNewline) {
				out += ".";
				lastWasNewline = false;
			}
		}
		return out;
	};
	return printable(head) + marker + printable(tail);
}

/* -------------------------------------------------------------------- *
 * Failure-mode active view (no ref, never claims durability)            *
 * -------------------------------------------------------------------- */

/**
 * Build an active view for the failure mode: persistence did NOT
 * succeed, no ref was issued, but the caller still needs a
 * bounded representation so it can surface the failure safely.
 *
 * The view is explicitly marked `non_recoverable=true` and the
 * `ref` field is `""` (empty). The excerpt is bounded and does
 * NOT pretend durability. This is the only accepted way to
 * produce a ToolResultActiveView without a successful
 * `writeToolResult`.
 */
export function buildFailureActiveView(
	bytes: Uint8Array,
	policy: ActiveViewPolicy,
	opts: {
		tool_name: string;
		reason: string;
	},
): {
	ref: "";
	non_recoverable: true;
	tool_name: string;
	original_bytes: number;
	excerpt: string;
	reason: string;
} {
	const excerpt = buildSafeBoundedText(bytes, policy);
	return {
		ref: "",
		non_recoverable: true,
		tool_name: opts.tool_name,
		original_bytes: bytes.length,
		excerpt,
		reason: opts.reason,
	};
}

/**
 * Build a bounded text excerpt for arbitrary bytes, without
 * claiming durability. Used by the failure-mode view. The
 * excerpt is the same head/tail window as the success path so
 * the failure view has the same shape discipline.
 */
export function buildSafeBoundedText(bytes: Uint8Array, policy: ActiveViewPolicy): string {
	const decoded = tryDecodeUtf8(bytes);
	if (bytes.length <= policy.maxExcerptBytes && decoded !== null) {
		return decoded;
	}
	if (decoded !== null) {
		const head = bytes.subarray(0, policy.headBytes);
		const tail = policy.tailBytes > 0 ? bytes.subarray(bytes.length - policy.tailBytes) : new Uint8Array();
		return new TextDecoder("utf-8", { fatal: true }).decode(head) +
			policy.marker +
			(policy.tailBytes > 0 ? new TextDecoder("utf-8", { fatal: true }).decode(tail) : "");
	}
	return lossySummary(bytes, policy);
}
